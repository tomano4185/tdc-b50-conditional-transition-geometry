def ensure_plan_pass(out: Path) -> Dict[str, Any]:
    p = out / "b50_9_plan_summary.json"
    if not p.exists():
        raise FileNotFoundError("Run --mode plan first")
    s = json.loads(p.read_text(encoding="utf-8"))
    if not bool(s.get("plan_integrity", {}).get("plan_pass", False)):
        raise RuntimeError(
            f"Frozen B50.9 plan did not pass: {s.get('plan_verdict')} — {s.get('reason')}"
        )
    return s


def extract_mode(args, b507) -> Dict[str, Any]:
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    plan_summary = ensure_plan_pass(out)

    plan_path = out / "b50_9_independent_window_plan.csv"
    plan = pd.read_csv(plan_path)
    prime_root = Path(args.independent_prime_root)

    # Freeze source provenance between PLAN and EXTRACT. We intentionally hash
    # the complete selected-file metadata manifest (segment id, basename, size,
    # mtime_ns), not the multi-terabyte corpus bytes. This is a fast integrity
    # gate; final operator-stack bytes are SHA-256 hashed after extraction.
    current_inv = scan_segment_files(prime_root)
    plan_segments = set(range(
        int(plan["start_segment"].min()),
        int(plan["end_segment"].max()) + 1,
    ))
    current_selected = current_inv[current_inv["segment_index"].isin(plan_segments)].copy()
    current_source_meta_hash = metadata_manifest_hash(current_selected)
    frozen_source_meta_hash = plan_summary["independent_source"].get("selected_source_metadata_sha256")
    if len(current_selected) != len(plan_segments):
        raise RuntimeError(
            f"INVALID_SOURCE_MANIFEST: expected {len(plan_segments)} source segments, "
            f"found {len(current_selected)}"
        )
    if current_source_meta_hash != frozen_source_meta_hash:
        raise RuntimeError(
            "INVALID_SOURCE_MANIFEST: independent source metadata changed after PLAN. "
            "Re-run PLAN only if you intentionally want a new frozen experiment."
        )

    b50 = b507.import_b50(Path(args.b50_script))

    with np.load(args.training_operator_stack, allow_pickle=False) as z:
        P_train = np.asarray(z["P_stack"], dtype=np.float64)
    expected_dim = int(P_train.shape[1])

    cache_dir = out / "operator_cache"
    cache_dir.mkdir(parents=True, exist_ok=True)
    staging_root = Path(args.staging_dir) if args.staging_dir else out / "_staging_hardlinks"
    staging_root.mkdir(parents=True, exist_ok=True)

    vectors: List[np.ndarray] = []
    meta_rows: List[Dict[str, Any]] = []
    status_rows: List[Dict[str, Any]] = []
    t_all = time.time()

    print("=== B50.9 INDEPENDENT-CORPUS OPERATOR EXTRACTION ===")
    print(f"windows      : {len(plan)}")
    print(f"prime root   : {prime_root}")
    print(f"operator dim : {expected_dim}")
    print(f"reuse cache  : {args.reuse_existing}")
    print(f"staging      : {staging_root}")

    for i, row in plan.iterrows():
        name = str(row["range_name"])
        cp = b507.cache_path(cache_dir, name)
        t0 = time.time()

        if args.reuse_existing and cp.exists():
            rec = b507.load_cache(cp, name, args.gap_bins)
            source = "cache"
        else:
            try:
                rec = b507.compute_operator_for_window(
                    b50,
                    prime_root,
                    staging_root,
                    row,
                    args.gap_bins,
                )
            except OSError as exc:
                if getattr(exc, "winerror", None) in (17, 1314) or getattr(exc, "errno", None) in (18,):
                    raise RuntimeError(
                        "Hardlink staging failed. Keep independent prime data on the same Windows volume "
                        "as the B50.9 output/staging directory, or provide --staging-dir on that volume."
                    ) from exc
                raise
            b507.save_cache(cp, rec, args.gap_bins)
            source = "recomputed"

        if int(rec["operator_dim"]) != expected_dim:
            raise RuntimeError(
                f"Operator dimension mismatch at {name}: {rec['operator_dim']} != {expected_dim}"
            )
        if int(rec["start_segment"]) != int(row["start_segment"]) or int(rec["end_segment"]) != int(row["end_segment"]):
            raise RuntimeError(f"Range bounds mismatch at {name}")

        vectors.append(np.asarray(rec["operator_vector"], dtype=np.float64))
        meta_rows.append({
            "range_index": int(i),
            "range_name": name,
            "start_segment": int(rec["start_segment"]),
            "end_segment": int(rec["end_segment"]),
            "n_primes": int(rec["n_primes"]),
            "n_gaps": int(rec["n_gaps"]),
            "mean_log_gap": float(rec["mean_log_gap"]),
            "gap_mean": float(rec["gap_mean"]),
            "gap_std": float(rec["gap_std"]),
        })
        status_rows.append({
            "range_index": int(i),
            "range_name": name,
            "source": source,
            "operator_dim": int(rec["operator_dim"]),
            "n_primes": int(rec["n_primes"]),
            "n_gaps": int(rec["n_gaps"]),
            "elapsed_seconds": float(time.time() - t0),
            "cache_path": str(cp),
        })

        print(
            f"[{i+1:03d}/{len(plan):03d}] {name} {source} "
            f"time={status_rows[-1]['elapsed_seconds']:.1f}s",
            flush=True,
        )

        if args.checkpoint_every and (i + 1) % args.checkpoint_every == 0:
            atomic_csv(out / "b50_9_extraction_status.csv", pd.DataFrame(status_rows))
            atomic_json(out / "b50_9_extraction_checkpoint.json", {
                "version": VERSION,
                "updated": now_s(),
                "completed": int(i + 1),
                "total": int(len(plan)),
                "last_range": name,
                "elapsed_seconds": float(time.time() - t_all),
            })

    shutil.rmtree(staging_root, ignore_errors=True)

    P_ext = np.vstack(vectors)
    labels = np.asarray([r["range_name"] for r in meta_rows])
    expected_shape = (len(plan), expected_dim)
    if P_ext.shape != expected_shape:
        raise RuntimeError(f"Independent stack shape {P_ext.shape} != {expected_shape}")
    labels_exact = labels.tolist() == plan["range_name"].astype(str).tolist()
    if not labels_exact:
        raise RuntimeError("Independent stack labels/order differ from frozen plan")

    stack_path = out / "b50_9_independent_operator_stack.npz"
    atomic_npz(
        stack_path,
        P_stack=P_ext,
        labels=labels,
        gap_bins=np.asarray([args.gap_bins], dtype=np.int64),
    )
    atomic_csv(out / "b50_9_operator_metadata.csv", pd.DataFrame(meta_rows))
    atomic_csv(out / "b50_9_extraction_status.csv", pd.DataFrame(status_rows))

    manifest = {
        "version": VERSION,
        "created": now_s(),
        "independent_prime_root": str(prime_root),
        "plan_csv": str(plan_path),
        "plan_csv_sha256": sha256_file(plan_path),
        "plan_summary_sha256": sha256_file(out / "b50_9_plan_summary.json"),
        "training_operator_stack": str(Path(args.training_operator_stack)),
        "training_operator_stack_sha256": sha256_file(Path(args.training_operator_stack)),
        "b50_script": str(Path(args.b50_script)),
        "b50_script_sha256": sha256_file(Path(args.b50_script)),
        "range_count": int(P_ext.shape[0]),
        "operator_dim": int(P_ext.shape[1]),
        "stack_shape": list(P_ext.shape),
        "gap_bins": int(args.gap_bins),
        "labels_exact_against_plan": labels_exact,
        "source_disjointness_plan_pass": bool(
            plan_summary["independent_source"]["source_disjoint_from_all_prior_b50_exposure"]
        ),
        "source_metadata_manifest_sha256": current_source_meta_hash,
        "source_metadata_exact_against_plan": True,
        "hardlink_only_policy": True,
        "elapsed_seconds": float(time.time() - t_all),
        "stack_sha256": sha256_file(stack_path),
    }
    atomic_json(out / "b50_9_extraction_manifest.json", manifest)
    print(f"[B50.9] stack saved: {stack_path} shape={P_ext.shape}")
    return manifest


