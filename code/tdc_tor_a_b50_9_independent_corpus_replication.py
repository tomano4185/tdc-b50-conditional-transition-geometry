def parse_args():
    p = argparse.ArgumentParser(description="B50.9 Independent-Corpus Replication")
    p.add_argument("--mode", choices=["plan", "extract", "audit", "all"], default="plan")

    p.add_argument("--b50-7-script", required=True)
    p.add_argument("--state-dataset", required=True)
    p.add_argument("--training-operator-stack", required=True)
    p.add_argument("--b50-script", required=True)
    p.add_argument("--b50-4-script", required=True)
    p.add_argument("--b50-4-protocol", required=True)
    p.add_argument("--b50-4-front-features", required=True)
    p.add_argument("--b50-6-summary", required=True)
    p.add_argument("--b50-7-dir", required=True)
    p.add_argument("--b50-8-dir", required=True)

    p.add_argument(
        "--independent-prime-root",
        default=r"d:\primes_output",
        help=(
            "Directory containing candidate source-disjoint prime segment files. "
            "It may be the same root if the database has been extended with new segment IDs."
        ),
    )
    p.add_argument(
        "--independent-start-segment",
        type=int,
        default=None,
        help=(
            "Engineering override only. Confirmatory default selects the earliest eligible contiguous run. "
            "Supplying this marks the protocol modified."
        ),
    )
    p.add_argument("--target-windows", type=int, default=FROZEN_TARGET_WINDOWS)
    p.add_argument("--output-dir", required=True)

    p.add_argument("--gap-bins", type=int, default=FROZEN_GAP_BINS)
    p.add_argument("--staging-dir", default=None)
    p.add_argument("--reuse-existing", action="store_true")
    p.add_argument("--checkpoint-every", type=int, default=10)

    p.add_argument("--controls-per-transition", type=int, default=FROZEN_CONTROLS)
    p.add_argument("--min-index-separation", type=int, default=FROZEN_MIN_INDEX_SEPARATION)
    p.add_argument("--randomization-replicates", type=int, default=FROZEN_RANDOMIZATION_REPLICATES)
    p.add_argument("--seed", type=int, default=FROZEN_SEED)

    a = p.parse_args()
    if a.target_windows < 6:
        p.error("--target-windows must be >=6")
    if a.gap_bins < 4:
        p.error("--gap-bins must be >=4")
    if a.controls_per_transition < 5:
        p.error("--controls-per-transition must be >=5")
    if a.min_index_separation < 3:
        p.error("--min-index-separation must be >=3")
    if a.randomization_replicates < 999:
        p.error("--randomization-replicates must be >=999")
    if a.checkpoint_every < 1:
        p.error("--checkpoint-every must be >=1")
    return a


def main():
    args = parse_args()
    b507 = import_b507(Path(args.b50_7_script))

    if args.mode == "plan":
        plan_mode(args, b507)
    elif args.mode == "extract":
        extract_mode(args, b507)
    elif args.mode == "audit":
        audit_mode(args, b507)
    elif args.mode == "all":
        plan_mode(args, b507)
        extract_mode(args, b507)
        audit_mode(args, b507)
    else:
        raise ValueError(args.mode)
    return 0


