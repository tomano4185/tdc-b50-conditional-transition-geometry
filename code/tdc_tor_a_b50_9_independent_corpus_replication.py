def validate_lineage(args) -> Dict[str, Any]:
    p6 = Path(args.b50_6_summary)
    p7 = Path(args.b50_7_dir) / "b50_7_summary.json"
    p8 = Path(args.b50_8_dir) / "b50_8_summary.json"
    for p in (p6, p7, p8):
        if not p.exists():
            raise FileNotFoundError(p)

    s6 = json.loads(p6.read_text(encoding="utf-8"))
    s7 = json.loads(p7.read_text(encoding="utf-8"))
    s8 = json.loads(p8.read_text(encoding="utf-8"))

    v6 = s6.get("final_verdict") == "PHYSICAL_ADJACENCY_SPECIFICITY_REPLICATED"
    v7 = s7.get("final_verdict") == "EXTERNAL_OFFSET_ADJACENCY_SPECIFICITY_REPLICATED"
    v8 = s8.get("final_verdict") == "MULTI_OFFSET_PHASE_ROBUST_EFFECT_INVARIANCE"

    e6 = float(s6.get("primary_specificity", {}).get("observed_mean_effect", float("nan")))
    e7 = float(s7.get("primary_replication", {}).get("observed_mean_effect", float("nan")))
    e8_mean = float(s8.get("effect_invariance", {}).get("new_offsets_mean_effect", float("nan")))
    e8_med = float(s8.get("effect_invariance", {}).get("new_offsets_median_effect", float("nan")))

    effects_negative = bool(
        np.isfinite(e6) and np.isfinite(e7) and np.isfinite(e8_mean)
        and e6 < 0 and e7 < 0 and e8_mean < 0
    )

    return {
        "b50_6_verdict": s6.get("final_verdict"),
        "b50_7_verdict": s7.get("final_verdict"),
        "b50_8_verdict": s8.get("final_verdict"),
        "b50_6_effect": e6,
        "b50_7_effect": e7,
        "b50_8_mean_effect": e8_mean,
        "b50_8_median_effect": e8_med,
        "verdicts_ok": bool(v6 and v7 and v8),
        "negative_reference_direction_ok": effects_negative,
        "pass": bool(v6 and v7 and v8 and effects_negative),
        "source_hashes": {
            "b50_6_summary": sha256_file(p6),
            "b50_7_summary": sha256_file(p7),
            "b50_8_summary": sha256_file(p8),
        },
    }


def original_geometry(b507, state: pd.DataFrame) -> Dict[str, Any]:
    ranges = [b507.parse_range_name(x) for x in state["range_name"].astype(str)]
    starts = np.asarray([a for a, _ in ranges], dtype=int)
    ends = np.asarray([b for _, b in ranges], dtype=int)
    lengths = ends - starts + 1
    steps = np.diff(starts)

    step_vals, step_counts = np.unique(steps, return_counts=True)
    len_vals, len_counts = np.unique(lengths, return_counts=True)
    step_i = int(np.argmax(step_counts))
    len_i = int(np.argmax(len_counts))
    step = int(step_vals[step_i])
    length = int(len_vals[len_i])
    step_frac = float(step_counts[step_i] / len(steps))
    length_frac = float(len_counts[len_i] / len(lengths))

    if step_frac < 0.95 or length_frac < 0.95:
        raise RuntimeError(
            f"Original geometry is not sufficiently uniform: step fraction={step_frac}, length fraction={length_frac}"
        )

    return {
        "ranges": ranges,
        "nominal_step": step,
        "nominal_length": length,
        "step_mode_fraction": step_frac,
        "length_mode_fraction": length_frac,
    }


def collect_prior_exposure(args, b507, state: pd.DataFrame) -> Tuple[Set[int], pd.DataFrame, Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    exposed: Set[int] = set()

    # Original B50 sequence.
    for idx, name in enumerate(state["range_name"].astype(str)):
        a, b = b507.parse_range_name(name)
        exposed.update(expand_interval(a, b))
        rows.append({
            "source_family": "B50_original",
            "source_file": str(Path(args.state_dataset)),
            "range_index": idx,
            "range_name": name,
            "start_segment": a,
            "end_segment": b,
        })

    # B50.7 +75 plan.
    p7 = Path(args.b50_7_dir) / "b50_7_offset_window_plan.csv"
    if not p7.exists():
        raise FileNotFoundError(p7)
    d7 = pd.read_csv(p7)
    for _, r in d7.iterrows():
        a, b = int(r["start_segment"]), int(r["end_segment"])
        exposed.update(expand_interval(a, b))
        rows.append({
            "source_family": "B50.7_plus75",
            "source_file": str(p7),
            "range_index": int(r.get("offset_range_index", len(rows))),
            "range_name": str(r["range_name"]),
            "start_segment": a,
            "end_segment": b,
        })

    # Every B50.8 offset subrun plan.
    b508_root = Path(args.b50_8_dir)
    plan_files = sorted(b508_root.glob("offset_*/b50_7_offset_window_plan.csv"))
    if len(plan_files) < 4:
        raise RuntimeError(
            f"Expected at least 4 B50.8 offset subrun plans under {b508_root}; found {len(plan_files)}"
        )
    for pf in plan_files:
        df = pd.read_csv(pf)
        family = f"B50.8_{pf.parent.name}"
        for _, r in df.iterrows():
            a, b = int(r["start_segment"]), int(r["end_segment"])
            exposed.update(expand_interval(a, b))
            rows.append({
                "source_family": family,
                "source_file": str(pf),
                "range_index": int(r.get("offset_range_index", len(rows))),
                "range_name": str(r["range_name"]),
                "start_segment": a,
                "end_segment": b,
            })

    exposure_df = pd.DataFrame(rows)
    if not exposed:
        raise RuntimeError("Prior exposure set is empty")

    exposure_summary = {
        "prior_exposed_segment_count": int(len(exposed)),
        "prior_exposed_min_segment": int(min(exposed)),
        "prior_exposed_max_segment": int(max(exposed)),
        "b50_8_subrun_plan_count": int(len(plan_files)),
        "source_families": sorted(exposure_df["source_family"].unique().tolist()),
    }
    return exposed, exposure_df, exposure_summary


